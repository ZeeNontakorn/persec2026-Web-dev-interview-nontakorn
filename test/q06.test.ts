import { describe, it, expect } from "vitest";
import { tribonacci } from "../src/q06-tribonacci";

/**
 * Q06 tribonacci — กรณีที่ทดสอบ
 *  1) ตัวอย่างจากโจทย์ (3 ข้อ)
 *  2) เคสที่เพิ่มเอง: ค่าเริ่มต้นว่าง, count = 0, count น้อยกว่าจำนวนค่าเริ่มต้น,
 *     ค่าเริ่มต้นไม่ครบ 3 ตัว (เติม 0 ให้ครบ และนับรวมในผลลัพธ์),
 *     มี 0 ในค่าเริ่มต้น, ลำดับยาว
 *  3) ไม่แก้ array ค่าเริ่มต้นของผู้เรียก
 */
describe("Q06 tribonacci", () => {
  it("ตัวอย่างโจทย์: ([1,3,5], 5) => [1,3,5,9,17]", () => {
    expect(tribonacci([1, 3, 5], 5)).toEqual([1, 3, 5, 9, 17]);
  });
  it("ตัวอย่างโจทย์: ([2,2,2], 3) => [2,2,2]", () => {
    expect(tribonacci([2, 2, 2], 3)).toEqual([2, 2, 2]);
  });
  it("ตัวอย่างโจทย์: ([10,10,10], 4) => [10,10,10,30]", () => {
    expect(tribonacci([10, 10, 10], 4)).toEqual([10, 10, 10, 30]);
  });

  it("เพิ่มเอง: ค่าเริ่มต้นว่าง ได้ 0 ล้วน", () => {
    expect(tribonacci([], 5)).toEqual([0, 0, 0, 0, 0]);
  });
  it("เพิ่มเอง: ([], 0) => []", () => {
    expect(tribonacci([], 0)).toEqual([]);
  });
  it("เพิ่มเอง: count = 0 ตัดค่าเริ่มต้นทิ้งด้วย", () => {
    expect(tribonacci([1, 3, 5], 0)).toEqual([]);
  });
  it("เพิ่มเอง: count น้อยกว่าจำนวนค่าเริ่มต้น ตัดให้เหลือ count ตัว", () => {
    expect(tribonacci([1, 3, 5], 2)).toEqual([1, 3]);
  });
  it("เพิ่มเอง: ค่าเริ่มต้นมี 1 ตัว เติม 0 ให้ครบ 3 แล้วนับรวม", () => {
    expect(tribonacci([1], 5)).toEqual([1, 0, 0, 1, 1]);
  });
  it("เพิ่มเอง: ค่าเริ่มต้นมี 0 ปนอยู่", () => {
    expect(tribonacci([5, 2, 0], 6)).toEqual([5, 2, 0, 7, 9, 16]);
  });
  it("เพิ่มเอง: ลำดับยาว", () => {
    expect(tribonacci([1, 1, 1], 8)).toEqual([1, 1, 1, 3, 5, 9, 17, 31]);
  });

  it("เพิ่มเอง: ไม่แก้ array ค่าเริ่มต้นของผู้เรียก", () => {
    const starter = [1, 3];
    tribonacci(starter, 6);
    expect(starter).toEqual([1, 3]);
  });
});
